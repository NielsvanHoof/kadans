#!/usr/bin/env bash
# Pull OCR / Transcribe stack outputs from Pulumi into env/profiles/aws.env,
# then apply that profile onto apps/platform/.env.
#
# A process on a laptop is not something AWS can hand a role to, so it uses a scoped
# IAM user instead. Neither is a Laravel Cloud container: the deployed application
# authenticates with the same long-lived key this script syncs (decision-10). Rotating
# it therefore means updating BOTH copies — see infra/README.md, "Rotating the
# application access key".
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PLATFORM_ROOT="$(cd "$ROOT/.." && pwd)"
ENV_FILE="${PLATFORM_ENV_FILE:-$PLATFORM_ROOT/.env}"
PROFILE_FILE="$PLATFORM_ROOT/env/profiles/aws.env"
APPLY_SCRIPT="$PLATFORM_ROOT/scripts/use-aws-profile.sh"

cd "$ROOT"

resolve_pulumi() {
  if [[ -x "$ROOT/node_modules/.bin/pulumi" ]]; then
    printf '%s' "$ROOT/node_modules/.bin/pulumi"
    return 0
  fi

  if command -v pulumi >/dev/null 2>&1; then
    command -v pulumi
    return 0
  fi

  return 1
}

if [[ "${LARAVEL_SAIL:-0}" == "1" ]]; then
  echo "sync-ocr-credentials.sh must run on the host (Pulumi + AWS credentials are outside Sail)." >&2
  echo "  cd apps/platform && composer env:aws" >&2
  echo "  # or: cd apps/platform/infra && ./scripts/sync-ocr-credentials.sh" >&2
  exit 1
fi

if ! PULUMI="$(resolve_pulumi)"; then
  echo "Pulumi CLI not found on PATH." >&2
  echo "Install it (e.g. brew install pulumi), then from apps/platform:" >&2
  echo "  composer env:aws" >&2
  echo "npm ci in infra installs the Pulumi SDK packages; the CLI is separate." >&2
  exit 1
fi

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Missing $ENV_FILE" >&2
  exit 1
fi

STACK="${PULUMI_STACK:-local}"

stack_output() {
  local name="$1"
  local show_secrets="${2:-}"
  if [[ "$show_secrets" == "--show-secrets" ]]; then
    "$PULUMI" stack output "$name" --stack "$STACK" --show-secrets
  else
    "$PULUMI" stack output "$name" --stack "$STACK"
  fi
}

ACCESS_KEY="$(stack_output ocrAccessKeyId --show-secrets)"
SECRET_KEY="$(stack_output ocrSecretAccessKey --show-secrets)"
BUCKET="$(stack_output documentsBucketName)"
TEXTRACT_TOPIC="$(stack_output textractSnsTopicArn)"
TEXTRACT_ROLE="$(stack_output textractPublishRoleArn)"
TEXTRACT_QUEUE="$(stack_output textractResultsQueueUrl)"
TRANSCRIBE_QUEUE="$(stack_output transcribeResultsQueueUrl)"

ACCESS_KEY="$(printf '%s' "$ACCESS_KEY" | tr -d '\r' | grep -Eo 'AKIA[0-9A-Z]{16}' | head -1)"
SECRET_KEY="$(printf '%s' "$SECRET_KEY" | tr -d '\r' | awk 'NF{print; exit}')"
BUCKET="$(printf '%s' "$BUCKET" | tr -d '\r' | awk 'NF{print; exit}')"
TEXTRACT_TOPIC="$(printf '%s' "$TEXTRACT_TOPIC" | tr -d '\r' | awk 'NF{print; exit}')"
TEXTRACT_ROLE="$(printf '%s' "$TEXTRACT_ROLE" | tr -d '\r' | awk 'NF{print; exit}')"
TEXTRACT_QUEUE="$(printf '%s' "$TEXTRACT_QUEUE" | tr -d '\r' | awk 'NF{print; exit}')"
TRANSCRIBE_QUEUE="$(printf '%s' "$TRANSCRIBE_QUEUE" | tr -d '\r' | awk 'NF{print; exit}')"

if [[ -z "$ACCESS_KEY" || -z "$SECRET_KEY" ]]; then
  echo "Could not read ocrAccessKeyId / ocrSecretAccessKey from stack \"$STACK\". Run: pulumi up -s $STACK" >&2
  exit 1
fi

if [[ -z "$BUCKET" || -z "$TEXTRACT_TOPIC" || -z "$TRANSCRIBE_QUEUE" ]]; then
  echo "Could not read document / Textract / Transcribe outputs from stack \"$STACK\". Run: pulumi up -s $STACK" >&2
  exit 1
fi

mkdir -p "$(dirname "$PROFILE_FILE")"

# Cached real-AWS overlay (gitignored). Re-apply later with: composer env:aws
cat > "$PROFILE_FILE" <<EOF
# Generated by infra/scripts/sync-ocr-credentials.sh from Pulumi stack $STACK — do not commit.
FILESYSTEM_DISK=s3
OCR_DRIVER=textract
TRANSCRIPTION_DRIVER=transcribe
AWS_ACCESS_KEY_ID=${ACCESS_KEY}
AWS_SECRET_ACCESS_KEY=${SECRET_KEY}
AWS_SESSION_TOKEN=
AWS_DEFAULT_REGION=eu-west-1
AWS_BUCKET=${BUCKET}
AWS_ENDPOINT=
AWS_URL=
AWS_USE_PATH_STYLE_ENDPOINT=false
TEXTRACT_SNS_TOPIC_ARN=${TEXTRACT_TOPIC}
TEXTRACT_SNS_ROLE_ARN=${TEXTRACT_ROLE}
TEXTRACT_RESULTS_QUEUE_URL=${TEXTRACT_QUEUE}
TRANSCRIBE_RESULTS_QUEUE_URL=${TRANSCRIBE_QUEUE}
EOF

chmod 600 "$PROFILE_FILE"

echo "Wrote cached AWS profile to $PROFILE_FILE (stack=$STACK)"
exec "$APPLY_SCRIPT" --apply-only aws
