<?php

declare(strict_types=1);

namespace App\Dossiers\Http\Requests\Builder\Concerns;

use App\Dossiers\Models\DocumentRequest;
use App\Dossiers\Models\Dossier;
use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Validation\Validator;

use function is_string;

/**
 * Shared validation for a questionnaire item's `configuration` payload.
 *
 * Creating and updating a field accept the same configuration shape, so both
 * requests validate it here rather than keeping two copies in step by hand.
 */
trait ValidatesQuestionnaireItemConfiguration
{
    /**
     * Option ids are UUIDs and visibility sources are ULID field keys. Both are
     * generated by us and never derived from labels, so renaming an option can
     * never silently rewire a condition.
     *
     * @return array<string, ValidationRule|array<mixed>|string>
     */
    protected function questionnaireConfigurationRules(): array
    {
        return [
            'configuration' => ['nullable', 'array'],
            'configuration.is_required' => ['sometimes', 'boolean'],
            'configuration.options' => ['sometimes', 'array', 'max:50'],
            'configuration.options.*.id' => ['required_with:configuration.options', 'uuid', 'distinct'],
            'configuration.options.*.label' => ['required_with:configuration.options', 'string', 'max:255'],
            'configuration.visibility' => ['nullable', 'array'],
            'configuration.visibility.source_field_key' => ['required_with:configuration.visibility', 'ulid'],
            'configuration.visibility.option_ids' => ['required_with:configuration.visibility', 'array', 'min:1', 'max:50'],
            'configuration.visibility.option_ids.*' => ['required', 'string', 'distinct'],
        ];
    }

    /**
     * Guards the "show this field when…" rule. The source must live in the same
     * dossier, sit earlier on the canvas, and be a type whose answer can be
     * matched. Requiring "earlier" is what keeps conditions from looping.
     *
     * Callers supply $isEarlier because they know the field's position
     * differently: an update compares against the saved record, while a create
     * compares against the requested insert position.
     *
     * @param  callable(DocumentRequest): bool  $isEarlier
     */
    protected function validateVisibilitySource(Validator $validator, callable $isEarlier): void
    {
        $sourceFieldKey = $this->input('configuration.visibility.source_field_key');
        $dossier = $this->route('dossier');

        if (! is_string($sourceFieldKey) || ! $dossier instanceof Dossier) {
            return;
        }

        $source = $dossier->documentRequestsInCanvasOrder()
            ->firstWhere('field_key', $sourceFieldKey);

        if (! $source instanceof DocumentRequest) {
            $this->addVisibilitySourceError($validator, __('The selected field could not be found.'));

            return;
        }

        if (! $isEarlier($source)) {
            $this->addVisibilitySourceError($validator, __('Visibility can only depend on an earlier field.'));

            return;
        }

        if (! $source->type->canDriveVisibility()) {
            $this->addVisibilitySourceError($validator, __('Visibility can only depend on a yes/no or choice field.'));
        }
    }

    private function addVisibilitySourceError(Validator $validator, string $message): void
    {
        $validator->errors()->add('configuration.visibility.source_field_key', $message);
    }
}
