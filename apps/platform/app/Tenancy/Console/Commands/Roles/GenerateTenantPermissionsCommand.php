<?php

declare(strict_types=1);

namespace App\Tenancy\Console\Commands;

use App\Tenancy\Contracts\TenantPermission;
use App\Tenancy\Support\PermissionRegistry;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

use function dirname;
use function Laravel\Prompts\info;
use function Laravel\Prompts\warning;

/**
 * Keeps the frontend TenantPermission union in sync with PermissionRegistry, so
 * the shared `permissions` prop is a closed Record and a mistyped permission
 * fails type checking instead of silently hiding UI.
 *
 * Mirrors questionnaire:generate-item-types.
 */
#[Signature('tenancy:generate-permissions {--check : Fail if the generated file is out of date}')]
#[Description('Generate the TypeScript TenantPermission union from the permission registry')]
final class GenerateTenantPermissionsCommand extends Command
{
    private const string RelativeOutputPath = 'js/types/generated/tenant-permissions.ts';

    public function __construct(private readonly PermissionRegistry $permissionRegistry)
    {
        parent::__construct();
    }

    public function handle(): int
    {
        $path = resource_path(self::RelativeOutputPath);
        $contents = $this->renderTypeScript();

        if ($this->option('check')) {
            if (! File::exists($path) || File::get($path) !== $contents) {
                warning('resources/'.self::RelativeOutputPath.' is out of date. Run: php artisan tenancy:generate-permissions');

                return self::FAILURE;
            }

            info('Tenant permission TypeScript is up to date.');

            return self::SUCCESS;
        }

        File::ensureDirectoryExists(dirname($path));
        File::put($path, $contents);

        info('Wrote resources/'.self::RelativeOutputPath);

        return self::SUCCESS;
    }

    private function renderTypeScript(): string
    {
        $valueLiterals = implode("\n", array_map(
            static fn (TenantPermission $permission): string => "    '{$permission->value}',",
            $this->permissionRegistry->all(),
        ));

        return <<<TS
/**
 * Auto-generated by `php artisan tenancy:generate-permissions`.
 * Do not edit by hand — add a case to the relevant domain's *Permission enum and
 * register it in config/tenant-permissions.php instead.
 */

export const TENANT_PERMISSIONS = [
{$valueLiterals}
] as const;

export type TenantPermission = (typeof TENANT_PERMISSIONS)[number];

/** Shape of the shared `permissions` Inertia prop. */
export type TenantPermissionMap = Record<TenantPermission, boolean>;

TS;
    }
}
