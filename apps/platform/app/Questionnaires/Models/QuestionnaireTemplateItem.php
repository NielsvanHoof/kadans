<?php

declare(strict_types=1);

namespace App\Questionnaires\Models;

use App\Questionnaires\Actions\Templates\NormalizeQuestionnaireItemConfigurationAction;
use App\Questionnaires\Enums\QuestionnaireItemType;
use Carbon\CarbonImmutable;
use Database\Factories\QuestionnaireTemplateItemFactory;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Str;
use Override;

/**
 * One question/document line inside a reusable template.
 *
 * PHPDoc is generated by `composer ide-helper`. field_key is nullable in DDL
 * for the backfill migration, but booted() always sets it — keep it as string.
 * configuration's element types are tightened after generation.
 *
 * @property int $id
 * @property int $questionnaire_template_id
 * @property QuestionnaireItemType $type
 * @property string $title
 * @property string|null $instructions
 * @property int $sort_order
 * @property CarbonImmutable|null $created_at
 * @property CarbonImmutable|null $updated_at
 * @property string $field_key
 * @property array<string, mixed>|null $configuration
 * @property-read QuestionnaireTemplate $template
 *
 * @method static QuestionnaireTemplateItemFactory factory($count = null, $state = [])
 * @method static Builder<static>|QuestionnaireTemplateItem newModelQuery()
 * @method static Builder<static>|QuestionnaireTemplateItem newQuery()
 * @method static Builder<static>|QuestionnaireTemplateItem query()
 * @method static Builder<static>|QuestionnaireTemplateItem whereConfiguration($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereCreatedAt($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereFieldKey($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereId($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereInstructions($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereQuestionnaireTemplateId($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereSortOrder($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereTitle($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereType($value)
 * @method static Builder<static>|QuestionnaireTemplateItem whereUpdatedAt($value)
 *
 * @mixin \Eloquent
 */
final class QuestionnaireTemplateItem extends Model
{
    /** @use HasFactory<QuestionnaireTemplateItemFactory> */
    use HasFactory;

    /**
     * @var list<string>
     */
    #[Override]
    protected $fillable = [
        'questionnaire_template_id',
        'type',
        'field_key',
        'title',
        'instructions',
        'configuration',
        'sort_order',
    ];

    /**
     * @var array<string, mixed>
     */
    #[Override]
    protected $attributes = [
        'type' => 'file',
        'sort_order' => 0,
    ];

    /**
     * @return BelongsTo<QuestionnaireTemplate, $this>
     */
    public function template(): BelongsTo
    {
        return $this->belongsTo(QuestionnaireTemplate::class, 'questionnaire_template_id');
    }

    #[Override]
    protected static function booted(): void
    {
        self::creating(function (self $item): void {
            $item->field_key ??= (string) Str::ulid();

            if ($item->configuration !== null) {
                return;
            }

            // Give every new item a normalized configuration, so nothing has to
            // guess defaults later when reading is_required or options.
            $item->configuration = resolve(
                NormalizeQuestionnaireItemConfigurationAction::class,
            )->handle($item->type, []);
        });
    }

    /**
     * @return array<string, string>
     */
    #[Override]
    protected function casts(): array
    {
        return [
            'type' => QuestionnaireItemType::class,
            'configuration' => 'array',
            'sort_order' => 'integer',
        ];
    }
}
