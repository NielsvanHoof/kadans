<?php

declare(strict_types=1);

namespace App\Questionnaires\Console\Commands;

use App\Questionnaires\Enums\QuestionnaireItemType;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

use function dirname;
use function Laravel\Prompts\info;
use function Laravel\Prompts\warning;

/**
 * Keeps the frontend QuestionnaireItemType union + capability flags in sync
 * with the PHP enum so staff / review / portal registries cannot drift on values.
 */
#[Signature('questionnaire:generate-item-types {--check : Fail if the generated file is out of date}')]
#[Description('Generate TypeScript questionnaire item-type values from the PHP enum')]
final class GenerateQuestionnaireItemTypesCommand extends Command
{
    private const string RelativeOutputPath = 'js/features/document-requests/item-types/generated.ts';

    public function handle(): int
    {
        $path = resource_path(self::RelativeOutputPath);
        $contents = $this->renderTypeScript();

        if ($this->option('check')) {
            if (! File::exists($path) || File::get($path) !== $contents) {
                warning('resources/'.self::RelativeOutputPath.' is out of date. Run: php artisan questionnaire:generate-item-types');

                return self::FAILURE;
            }

            info('Questionnaire item-type TypeScript is up to date.');

            return self::SUCCESS;
        }

        File::ensureDirectoryExists(dirname($path));
        File::put($path, $contents);

        info('Wrote resources/'.self::RelativeOutputPath);

        return self::SUCCESS;
    }

    private function renderTypeScript(): string
    {
        $values = QuestionnaireItemType::values();
        $valueLiterals = implode(",\n    ", array_map(
            static fn (string $value): string => "'{$value}'",
            $values,
        ));

        $capabilityLines = [];

        foreach (QuestionnaireItemType::cases() as $case) {
            $storesAnswerText = $case->storesAnswerText() ? 'true' : 'false';
            $storesAnswerOptionIds = $case->storesAnswerOptionIds() ? 'true' : 'false';
            $canDriveVisibility = $case->canDriveVisibility() ? 'true' : 'false';

            $capabilityLines[] = "    {$case->value}: {";
            $capabilityLines[] = "        storesAnswerText: {$storesAnswerText},";
            $capabilityLines[] = "        storesAnswerOptionIds: {$storesAnswerOptionIds},";
            $capabilityLines[] = "        canDriveVisibility: {$canDriveVisibility},";
            $capabilityLines[] = '    },';
        }

        $capabilitiesBlock = implode("\n", $capabilityLines);
        $yesId = QuestionnaireItemType::BooleanYesOptionId;
        $noId = QuestionnaireItemType::BooleanNoOptionId;

        return <<<TS
/**
 * Auto-generated by `php artisan questionnaire:generate-item-types`.
 * Do not edit by hand — change App\\Questionnaires\\Enums\\QuestionnaireItemType instead.
 */

export const QUESTIONNAIRE_ITEM_TYPES = [
    {$valueLiterals},
] as const;

export type QuestionnaireItemType = (typeof QUESTIONNAIRE_ITEM_TYPES)[number];

export const BOOLEAN_YES_OPTION_ID = '{$yesId}';

export const BOOLEAN_NO_OPTION_ID = '{$noId}';

export type QuestionnaireItemTypeCapabilities = {
    storesAnswerText: boolean;
    storesAnswerOptionIds: boolean;
    canDriveVisibility: boolean;
};

export const questionnaireItemTypeCapabilities = {
{$capabilitiesBlock}
} as const satisfies Record<
    QuestionnaireItemType,
    QuestionnaireItemTypeCapabilities
>;

TS;
    }
}
